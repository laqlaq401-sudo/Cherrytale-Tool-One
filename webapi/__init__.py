"""webapi 包：Web 前端的后端层（本次 Web 化新增）。

【它负责什么】
把 ``services/runner.py`` 的**同一个**调度入口暴露成 HTTP 接口，并把
"任务执行过程中说的话"变成前端能实时看到的东西：

==========================  ==================================================
模块                          职责
==========================  ==================================================
``logstream.py``             **日志流**：内存环形缓冲（``seq`` 增量游标）+
                             logging Handler + 线程感知的 ``print`` 桥。
``state.py``                 **运行状态**：当前跑到哪一步、每一步成功/失败，
                             以及"同一时刻只允许一次运行"的锁。
``app.py``                   **FastAPI 应用**：路由、token 鉴权、静态目录挂载。
==========================  ==================================================

【与其它层的关系（依赖方向永远是单向的）】

    web_server.py / main_gui.py    ← 进程入口（端口、窗口）
            ↓
    webapi/（HTTP 与呈现）          ← 本包
            ↓
    services/（装配与执行）         ← 与 CLI 共用
            ↓
    tasks/ → client/ → （网络）

.. note::
   本包**不做任何业务判断**：能不能花钱、参数合不合法、要不要只读，
   全部由 ``services/runner.py`` 决定。这样"网页上的行为"与"命令行的行为"
   只可能同时改变，不可能各自漂移。
"""

