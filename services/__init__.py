"""services 包：CLI 与 Web 共用的**调度层**（本次 Web 化新增）。

【它解决的问题】
Web 化之前，"跑一个任务"这件事完整地写在 ``main.py`` 的 ``cmd_run()`` 里：
载入会话状态 → 组装钻石闸门（``SpendPolicy``）→ 组装运行参数（``RunOptions``）
→ 按任务声明过滤专属参数 → 执行 → 汇总结果。

如果 Web 层（``webapi/``）自己再写一遍这段逻辑，就出现了**两份**决定
"会不会花钻石""battles=0 是不是只读"的代码。这类分叉最危险：改了一处、
忘了另一处，表现是"命令行安全、网页上却真的花掉了资源"，而且不会有任何报错。

于是把它抽成一层：

    main.py（CLI 薄入口）  ─┐
                            ├─→ services/ ─→ tasks/ ─→ client/ ─→ （网络）
    webapi/（HTTP 薄入口）  ─┘                  ↘ models/（报文）
                                                ↘ crypto/（签名）

【两个文件，两类职责】
==========================  ==================================================
模块                          职责
==========================  ==================================================
``task_spec.py``             **参数面唯一来源**：每个任务接受哪些参数、默认值、
                             是否"会消耗资源"、在 UI 里归到哪一组。
``runner.py``                **执行调度**：结构化 ``RunRequest`` → 会话/闸门/
                             运行参数装配 → 串行执行 → ``RunReport``。
==========================  ==================================================

【为什么入口层"薄"是件好事】
入口只做两件事：把外部输入翻译成 :class:`services.runner.RunRequest`
（CLI 翻译 argparse、HTTP 翻译 JSON），把结果渲染到自己的出口
（CLI 打印到 stdout、HTTP 转成 JSON + 日志流）。
凡是"判断"（能不能花钱、参数合不合法、要不要执行）都在本层，不在入口层。

.. note::
   本包**不导入** ``main.py``，也不被 ``main.py`` 之外的入口重复实现 ——
   依赖方向永远是 ``入口 → services → tasks → client``，不会出现反向依赖。
"""

